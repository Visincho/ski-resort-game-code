// Builds dist/ for static hosting (Cloudflare Pages): the client plus the baked terrain tiles and
// OpenStreetMap files of every famous resort, taken from cache/ (run `npm run warm` first).
// Usage: npm run build:static            SNOWLINE_API=https://api.example.com npm run build:static
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FAMOUS_RESORTS } from '../public/js/shared/resorts.js';
import { GeoProjection } from '../public/js/util.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'public');
const DIST = path.join(ROOT, 'dist');
const CACHE = process.env.CACHE_DIR || path.join(ROOT, 'cache');
const API = process.env.SNOWLINE_API || '';

const lonToX = (lon, z) => ((lon + 180) / 360) * 2 ** z;
const latToY = (lat, z) => { const r = lat * Math.PI / 180; return ((1 - Math.log(Math.tan(r) + 1 / Math.cos(r)) / Math.PI) / 2) * 2 ** z; };
const exists = (f) => fs.access(f).then(() => true, () => false);

await fs.rm(DIST, { recursive: true, force: true });
await fs.cp(SRC, DIST, { recursive: true });
await fs.writeFile(path.join(DIST, 'config.js'),
  `// Generated by tools/build-static.mjs\nwindow.SNOWLINE_CONFIG = { apiBase: ${JSON.stringify(API)} };\n`);

const tiles = new Set(), osm = new Set();
for (const r of FAMOUS_RESORTS) {
  const p = new GeoProjection(r.lat, r.lon);
  const W = r.w * 1000, H = r.h * 1000;
  const [n] = p.toLatLon(0, -H / 2), [s] = p.toLatLon(0, H / 2), [, w] = p.toLatLon(-W / 2, 0), [, e] = p.toLatLon(W / 2, 0);
  // same zoom choice as the client (terrain.js) and warm-cache.mjs
  let z = 13;
  const count = zz => (Math.floor(lonToX(e, zz)) - Math.floor(lonToX(w, zz)) + 1) * (Math.floor(latToY(s, zz)) - Math.floor(latToY(n, zz)) + 1);
  while (z > 10 && count(z) > 42) z--;
  for (let ty = Math.floor(latToY(n, z)); ty <= Math.floor(latToY(s, z)); ty++)
    for (let tx = Math.floor(lonToX(w, z)); tx <= Math.floor(lonToX(e, z)); tx++) tiles.add(`${z}/${tx}/${ty}.png`);
  osm.add([s, w, n, e].map(v => v.toFixed(4)).join('_') + '.json');
}

let bytes = 0, missingTiles = 0, missingOsm = 0;
async function copyOne(rel, from, to) {
  const src = path.join(CACHE, from, rel);
  if (!(await exists(src))) return false;
  const dst = path.join(DIST, to, rel);
  await fs.mkdir(path.dirname(dst), { recursive: true });
  await fs.copyFile(src, dst);
  bytes += (await fs.stat(src)).size;
  return true;
}
for (const t of tiles) if (!(await copyOne(t, 'tiles', 'tiles'))) missingTiles++;
for (const o of osm) if (!(await copyOne(o, 'osm', 'osm'))) missingOsm++;

console.log(`dist/ ready: ${tiles.size - missingTiles}/${tiles.size} tiles, ${osm.size - missingOsm}/${osm.size} OSM files, ` +
  `${(bytes / 1e6).toFixed(1)} MB baked. API base: ${API || '(none: universe disabled)'}`);
if (missingTiles || missingOsm) console.log('Some data is missing: start the server and run `npm run warm`, then rebuild. Missing resorts still load live from AWS / Overpass.');
