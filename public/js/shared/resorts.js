// Rough climate defaults for any new place on Earth.
export function defaultClimate(lat) {
  const a = Math.abs(lat);
  const t1500 = 16 - 0.45 * a; // 46 deg -> -4.7, 39 -> -1.5, 63 -> -12
  let treeline;
  if (a < 40) treeline = 3500;
  else if (a < 46) treeline = 3500 - (a - 40) * 233;
  else treeline = Math.max(600, 2100 - (a - 46) * 70);
  return { climate: { t1500, snow: 1.0 }, treeline };
}
